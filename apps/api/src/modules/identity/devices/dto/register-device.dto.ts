import { ApiProperty, ApiPropertyOptional } from "@nestjs/swagger";
import { IsEnum, IsNotEmpty, IsOptional, IsString } from "class-validator";
import { DevicePlatform } from "@mastara/database";

export class RegisterDeviceDto {
  @ApiProperty({
    example: "device-uuid-9876-5432-1098",
    description: "Unique device identifier generated by mobile hardware/OS",
  })
  @IsString()
  @IsNotEmpty()
  deviceId!: string;

  @ApiPropertyOptional({
    example: "Samsung Galaxy A54",
    description: "Human readable device name/model",
  })
  @IsOptional()
  @IsString()
  deviceName?: string;

  @ApiPropertyOptional({
    enum: DevicePlatform,
    default: DevicePlatform.ANDROID,
    description: "Mobile operating system platform (ANDROID | IOS)",
  })
  @IsOptional()
  @IsEnum(DevicePlatform)
  platform?: DevicePlatform;
}
