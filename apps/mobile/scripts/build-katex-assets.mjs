// apps/mobile/scripts/build-katex-assets.mjs
// Builds src/core/math/katexAssets.generated.ts: the KaTeX stylesheet with the fonts embedded as data URIs,
// so formulas draw with no network. Runs before start / typecheck. Usage: node scripts/build-katex-assets.mjs [--katex-dir <path>]
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, '../src/core/math/katexAssets.generated.ts');

/** Fonts kept in the app. The rest (Fraktur, Script, Typewriter, SansSerif, Caligraphic-Bold) are rarely used in freshman maths. */
const KEEP = new Set([
  'KaTeX_Main-Regular',
  'KaTeX_Main-Bold',
  'KaTeX_Main-Italic',
  'KaTeX_Main-BoldItalic',
  'KaTeX_Math-Italic',
  'KaTeX_Math-BoldItalic',
  'KaTeX_AMS-Regular',
  'KaTeX_Size1-Regular',
  'KaTeX_Size2-Regular',
  'KaTeX_Size3-Regular',
  'KaTeX_Size4-Regular',
  'KaTeX_Caligraphic-Regular',
]);

function findKatexDir() {
  const flag = process.argv.indexOf('--katex-dir');
  if (flag !== -1 && process.argv[flag + 1]) return resolve(process.argv[flag + 1]);
  try {
    return dirname(createRequire(import.meta.url).resolve('katex/package.json'));
  } catch {
    console.error('katex is not installed. Run `npm install` at the repo root first.');
    process.exit(1);
  }
}

const katexDir = findKatexDir();
const version = JSON.parse(readFileSync(join(katexDir, 'package.json'), 'utf8')).version;
let css = readFileSync(join(katexDir, 'dist', 'katex.min.css'), 'utf8');

let kept = 0;
let fontBytes = 0;

css = css.replace(/@font-face\{[^}]*\}/g, (block) => {
  const file = /url\(fonts\/([^)]+)\.woff2\)/.exec(block)?.[1];
  if (!file || !KEEP.has(file)) return ''; // drop fonts we do not ship
  const data = readFileSync(join(katexDir, 'dist', 'fonts', `${file}.woff2`));
  fontBytes += data.length;
  kept += 1;
  // Keep only the woff2 source (Android and iOS web views both support it).
  return block.replace(/src:[^;}]*/, `src:url(data:font/woff2;base64,${data.toString('base64')}) format("woff2")`);
});

if (css.includes('fonts/')) {
  console.error('KaTeX stylesheet still points at font files. The KaTeX file format changed; update this script.');
  process.exit(1);
}
if (kept !== KEEP.size) {
  console.error(`Expected ${KEEP.size} fonts, embedded ${kept}. The KaTeX font list changed; update KEEP.`);
  process.exit(1);
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// apps/mobile/src/core/math/katexAssets.generated.ts\n` +
    `// GENERATED by scripts/build-katex-assets.mjs from katex ${version}. Do not edit or commit.\n` +
    `export const KATEX_VERSION = ${JSON.stringify(version)};\n` +
    `export const KATEX_CSS = ${JSON.stringify(css)};\n`,
);

console.log(`KaTeX ${version}: ${kept} fonts (${Math.round(fontBytes / 1024)} KB woff2), stylesheet ${Math.round(css.length / 1024)} KB -> ${outFile}`);

// Ensure expo-sqlite Android JSI SharedObject patch is applied before bundler starts
try {
  const patchScript = resolve(here, '../../../scripts/patch-expo-sqlite.mjs');
  await import(patchScript);
} catch {
  // ignore
}
